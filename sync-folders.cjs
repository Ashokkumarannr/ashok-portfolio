const fs = require('fs');
const path = require('path');

const rootDir = __dirname;
const publicDir = path.join(rootDir, 'public');
const assetsDir = path.join(publicDir, 'assets');

if (!fs.existsSync(assetsDir)) {
  fs.mkdirSync(assetsDir, { recursive: true });
}

const folderMap = {
  cricketer: { category: 'social-media', sub: 'sport-brand', dir: 'cricketer', name: 'Sport Brand' },
  theunioa: { category: 'social-media', sub: 'freelancing-platform', dir: 'theunioa', name: 'Freelancing Platform' },
  education: { category: 'social-media', sub: 'education-industry', dir: 'education', name: 'Education Industry' },
  resturant: { category: 'social-media', sub: 'restaurant-industry', dir: 'resturant', name: 'Restaurant Industry' },
  'teal holidyas': { category: 'social-media', sub: 'tour-industry', dir: 'teal holidyas', name: 'Tour Industry' },
  stockmarket: { category: 'social-media', sub: 'stockmarket', dir: 'stockmarket', name: 'Stockmarket' },
  'kids cloth': { category: 'social-media', sub: 'kids-cloth', dir: 'kids cloth', name: 'Kids Cloth' },
  'brand detail': { category: 'branding', sub: 'genzo', dir: 'brand detail', name: 'Genzo Brand Document' },
  p2: { category: 'branding', sub: 'zendo', dir: 'p2', name: 'Zendo' },
  package: { category: 'packaging', dir: 'package', name: 'Packaging' },
  presentation: { category: 'pitchdeck', dir: 'presentation', name: 'Pitch Deck' }
};

const imageExts = new Set(['.jpg', '.jpeg', '.png', '.webp', '.svg', '.gif']);

const result = {};

const userDownloads = 'C:\\Users\\SS\\Downloads';
const downloadFolderAliases = {
  'brand detail': ['BRAND DETAIL', 'brand detail'],
  'p2': ['p2'],
  'package': ['package'],
  'presentation': ['presentation', 'presenation'],
  'stockmarket': ['Javeed-20261114T062116Z-1-001/Javeed', 'Javeed-20261114T062116Z-1-001\\Javeed', 'Javeed', 'javeed'],
  'kids cloth': ['Samino-20261114T062424Z-1-001/Samino', 'Samino-20261114T062424Z-1-001\\Samino', 'Samino', 'samino']
};

for (const [folderName, meta] of Object.entries(folderMap)) {
  const targetFolder = path.join(assetsDir, folderName);

  if (!fs.existsSync(targetFolder)) {
    fs.mkdirSync(targetFolder, { recursive: true });
  }

  // Check Downloads directory for files if available
  const aliases = downloadFolderAliases[folderName] || [folderName];
  for (const alias of aliases) {
    const dlPath = path.join(userDownloads, alias);
    if (fs.existsSync(dlPath)) {
      try {
        const dlFiles = fs.readdirSync(dlPath);
        for (const file of dlFiles) {
          const s = path.join(dlPath, file);
          if (fs.statSync(s).isFile() && imageExts.has(path.extname(file).toLowerCase())) {
            const dest = path.join(targetFolder, file);
            if (!fs.existsSync(dest)) {
              try { fs.copyFileSync(s, dest); } catch (e) {}
            }
          }
        }
      } catch (e) {}
    }
  }

  // Read images directly from public/assets/<folderName>
  const pubFiles = fs.readdirSync(targetFolder)
    .filter(f => imageExts.has(path.extname(f).toLowerCase()))
    .sort((a, b) => a.localeCompare(b, undefined, { numeric: true, sensitivity: 'base' }));

  result[folderName] = pubFiles.map((file, idx) => {
    const baseName = path.parse(file).name;
    const thumbRel = `/assets/_thumbs/${folderName}/${baseName}.jpg`;
    const thumbAbs = path.join(assetsDir, '_thumbs', folderName, `${baseName}.jpg`);
    const hasThumb = fs.existsSync(thumbAbs);
    return {
      path: `/assets/${folderName}/${file}`,
      thumb: hasThumb ? thumbRel : `/assets/${folderName}/${file}`,
      fullPath: `/assets/${folderName}/${file}`,
      title: String(idx + 1)
    };
  });
}

// Generate thumbnails if needed
const { execSync } = require('child_process');
try {
  execSync('powershell -ExecutionPolicy Bypass -File generate-thumbnails.ps1', { stdio: 'inherit' });
} catch (e) {}

const outputPath = path.join(rootDir, 'src', 'dynamicFolders.js');
const fileContent = `// Auto-generated by sync-folders.cjs
export const dynamicFolderData = ${JSON.stringify(result, null, 2)};
`;

fs.writeFileSync(outputPath, fileContent, 'utf8');
console.log('Successfully synced all media folders into single public/assets/ directory:');
for (const [k, files] of Object.entries(result)) {
  console.log(` - ${k}: ${files.length} images`);
}

